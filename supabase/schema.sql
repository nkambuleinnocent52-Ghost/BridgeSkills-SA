-- Run once in Supabase SQL Editor. Safe to rerun; it does not erase accounts or work.
-- This private schema is NOT added to Supabase's exposed Data API schemas.
BEGIN;
CREATE SCHEMA IF NOT EXISTS skillbridge;
REVOKE ALL ON SCHEMA skillbridge FROM PUBLIC;
  
 CREATE TABLE IF NOT EXISTS skillbridge.users (
 id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL,
 name TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('talent','business')),
 headline TEXT NOT NULL DEFAULT '', location TEXT NOT NULL DEFAULT '', bio TEXT NOT NULL DEFAULT '',
 skills TEXT NOT NULL DEFAULT '[]', share_public INTEGER NOT NULL DEFAULT 0,
 passport_token TEXT UNIQUE NOT NULL, created_at TEXT NOT NULL
 );
 CREATE TABLE IF NOT EXISTS skillbridge.sessions (token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES skillbridge.users(id) ON DELETE CASCADE, expires_at TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS skillbridge.tasks (
 id TEXT PRIMARY KEY, business_id TEXT NOT NULL REFERENCES skillbridge.users(id), title TEXT NOT NULL, description TEXT NOT NULL,
 category TEXT NOT NULL, skills TEXT NOT NULL, budget INTEGER NOT NULL CHECK(budget>=100), deadline TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','assigned','submitted','completed')), created_at TEXT NOT NULL
 );
 CREATE TABLE IF NOT EXISTS skillbridge.applications (
 id TEXT PRIMARY KEY, task_id TEXT NOT NULL REFERENCES skillbridge.tasks(id), talent_id TEXT NOT NULL REFERENCES skillbridge.users(id), pitch TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'applied' CHECK(status IN ('applied','assigned','not_selected','submitted','changes_requested','completed')),
 submission TEXT NOT NULL DEFAULT '', work_url TEXT NOT NULL DEFAULT '', public_consent INTEGER NOT NULL DEFAULT 0,
 feedback TEXT NOT NULL DEFAULT '', applied_at TEXT NOT NULL, updated_at TEXT NOT NULL, UNIQUE(task_id,talent_id)
 );
 CREATE TABLE IF NOT EXISTS skillbridge.evidence (
 id TEXT PRIMARY KEY, talent_id TEXT NOT NULL REFERENCES skillbridge.users(id), title TEXT NOT NULL, organisation TEXT NOT NULL,
 description TEXT NOT NULL, skills TEXT NOT NULL, work_url TEXT NOT NULL DEFAULT '', period TEXT NOT NULL,
 public_consent INTEGER NOT NULL DEFAULT 0, revision INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL, updated_at TEXT NOT NULL
 );
 CREATE TABLE IF NOT EXISTS skillbridge.evidence_versions (
 evidence_id TEXT NOT NULL REFERENCES skillbridge.evidence(id) ON DELETE CASCADE, revision INTEGER NOT NULL,
 title TEXT NOT NULL, organisation TEXT NOT NULL, description TEXT NOT NULL, skills TEXT NOT NULL, work_url TEXT NOT NULL, period TEXT NOT NULL, created_at TEXT NOT NULL,
 PRIMARY KEY(evidence_id,revision)
 );
 CREATE TABLE IF NOT EXISTS skillbridge.confirmations (
 rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 id TEXT PRIMARY KEY, evidence_id TEXT NOT NULL REFERENCES skillbridge.evidence(id) ON DELETE CASCADE, requester_id TEXT NOT NULL REFERENCES skillbridge.users(id),
 receiver_id TEXT NOT NULL REFERENCES skillbridge.users(id), revision INTEGER NOT NULL,
 status TEXT NOT NULL CHECK(status IN ('requested','confirmed','declined','withdrawn','superseded')),
 statement TEXT NOT NULL DEFAULT '', relationship TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL, responded_at TEXT,
 UNIQUE(evidence_id,receiver_id,revision)
 );
 CREATE TABLE IF NOT EXISTS skillbridge.events (
 rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 id TEXT PRIMARY KEY, application_id TEXT NOT NULL REFERENCES skillbridge.applications(id), actor_id TEXT NOT NULL REFERENCES skillbridge.users(id),
 action TEXT NOT NULL, detail TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL
 );
 CREATE TABLE IF NOT EXISTS skillbridge.reports (
 id TEXT PRIMARY KEY, reporter_id TEXT NOT NULL REFERENCES skillbridge.users(id), target_type TEXT NOT NULL CHECK(target_type IN ('task','skillbridge.evidence','passport')),
 target_id TEXT NOT NULL, reason TEXT NOT NULL, created_at TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'open'
 );
 CREATE INDEX IF NOT EXISTS confirmation_receiver ON skillbridge.confirmations(receiver_id);
 CREATE INDEX IF NOT EXISTS application_talent ON skillbridge.applications(talent_id);
 CREATE INDEX IF NOT EXISTS evidence_talent ON skillbridge.evidence(talent_id);

 
CREATE TABLE IF NOT EXISTS skillbridge.rate_limits (key TEXT PRIMARY KEY,hits INTEGER NOT NULL,window_end BIGINT NOT NULL);

ALTER TABLE skillbridge.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE skillbridge.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE skillbridge.tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE skillbridge.applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE skillbridge.evidence ENABLE ROW LEVEL SECURITY;
ALTER TABLE skillbridge.evidence_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE skillbridge.confirmations ENABLE ROW LEVEL SECURITY;
ALTER TABLE skillbridge.events ENABLE ROW LEVEL SECURITY;
ALTER TABLE skillbridge.reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE skillbridge.rate_limits ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA skillbridge FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA skillbridge FROM PUBLIC;
DO $$
DECLARE role_name TEXT;
BEGIN
  FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA skillbridge FROM %I', role_name);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA skillbridge FROM %I', role_name);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA skillbridge FROM %I', role_name);
    END IF;
  END LOOP;
END $$;
COMMIT;
